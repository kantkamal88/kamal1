public class AddTwoNumbers {
    public static void main(String[] args) {
        // declare two numbers
        int num1 = 10;
        int num2 = 20;

        // add them
        int sum = num1 + num2;

        // print result
        System.out.println("The sum of " + num1 + " and " + num2 + " is: " + sum);
    }
}